package io.github.jbellis.jvector.vector;

import io.github.jbellis.jvector.vector.cnative.LibraryLoader;
import io.github.jbellis.jvector.vector.cnative.NativeAshOneDnn;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.invoke.MethodHandle;

/**
 * Availability of the optional oneDNN ASH add-on, whose bindings are generated by jextract
 * into {@link NativeAshOneDnn}. Generated bindings resolve each symbol on first call, so
 * callers check here first: older add-on libraries may lack newer entry points.
 */
final class NativeASHAddOn {
    private static final boolean LOADED = LibraryLoader.loadAshFp16();

    private NativeASHAddOn() {}

    /** Null if the add-on loaded, reports ABI 1 and exports every named symbol; otherwise why not. */
    static String unavailable(String... symbols) {
        return LOADED ? unavailable(SymbolLookup.loaderLookup(), symbols) : "library not loaded";
    }

    /** Null if {@code lookup} reports ABI 1 and exports every named symbol; otherwise why not. */
    static String unavailable(SymbolLookup lookup, String... symbols) {
        int version;
        try {
            MemorySegment abi = lookup.find("jvector_ash_fp16_abi").orElse(null);
            if (abi == null) return "missing symbol jvector_ash_fp16_abi";
            MethodHandle handle = Linker.nativeLinker().downcallHandle(abi,
                    NativeAshOneDnn.jvector_ash_fp16_abi$descriptor());
            version = (int) handle.invokeExact();
        } catch (UnsatisfiedLinkError | IllegalCallerException | SecurityException
                 | UnsupportedOperationException unavailable) {
            return unavailable.toString();
        } catch (RuntimeException | Error failure) {
            throw failure;
        } catch (Throwable failure) {
            throw new AssertionError("Unexpected ASH add-on ABI failure", failure);
        }
        if (version != 1) return "add-on ABI " + version + ", expected 1";
        for (String symbol : symbols)
            if (lookup.find(symbol).isEmpty()) return "missing symbol " + symbol;
        return null;
    }
}
