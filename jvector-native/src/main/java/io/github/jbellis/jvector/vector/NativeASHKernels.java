package io.github.jbellis.jvector.vector;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.invoke.MethodHandle;
import java.util.Objects;

import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_FLOAT;
import static java.lang.foreign.ValueLayout.JAVA_INT;

/**
 * Checked, synchronous FFM access to the C=1 Highway neighborhood kernel.
 *
 * <p>Keep this hand-written binding outside {@code cnative}, which is generated by jextract.
 * Ordinary graph neighborhoods use a bounded critical downcall and access heap arrays directly.
 * Larger inputs use one ordinary downcall with temporary native storage, allowing the JVM to
 * reach safepoints during longer native work. Neither path retains pointers or calls Java.</p>
 *
 * <p>The ASH symbol is optional for compatibility with libraries predating this kernel.
 * Capability detection leaves the provider's Java LUT path available when it is absent.</p>
 */
final class NativeASHKernels {
    private static final boolean TRACE_DOWNCALLS = Boolean.getBoolean("jextract.trace.downcalls");
    private static final String SYMBOL = "ash_score_neighborhood_c1_f32";
    private static final int HEADER_BYTES_PER_LANE = 5;
    private static final int LUT_ENTRIES_PER_GROUP = 16;

    // Bound critical-call work independently of CPU model, clock speed, and graph degree.
    // Charge masked/padded vector lanes as well as active lanes. This is a conservative
    // work budget, not a measured timing guarantee or an optimized copying crossover.
    static final int MAX_CRITICAL_LANE_GROUPS = 1 << 16;

    private static final MemorySegment ADDRESS_OF_KERNEL = SymbolLookup.loaderLookup().find(SYMBOL).orElse(null);
    private static final FunctionDescriptor DESCRIPTOR =
            FunctionDescriptor.of(JAVA_INT, ADDRESS, ADDRESS, JAVA_FLOAT, JAVA_INT, JAVA_INT, JAVA_INT, ADDRESS);
    private static final MethodHandle CRITICAL_SCORE = ADDRESS_OF_KERNEL == null
            ? null
            : Linker.nativeLinker().downcallHandle(ADDRESS_OF_KERNEL, DESCRIPTOR, Linker.Option.critical(true));
    private static final MethodHandle ORDINARY_SCORE =
            ADDRESS_OF_KERNEL == null ? null : Linker.nativeLinker().downcallHandle(ADDRESS_OF_KERNEL, DESCRIPTOR);

    private NativeASHKernels() {}

    /**
     * Detect the optional ASH entry after the provider has loaded its supporting library.
     * Older libraries can still provide their existing operations and the Java LUT fallback.
     */
    static boolean isAvailable() {
        return ADDRESS_OF_KERNEL != null;
    }

    /** Validate all Java-side size and aliasing contracts before passing pointers to C++. */
    static void scoreNeighborhood(
            byte[] codes, int groups, int blockSize, int capacity, float[] lut, float landmarkDot, float[] out) {
        if (!isAvailable()) {
            throw new UnsupportedOperationException("Native library does not provide " + SYMBOL);
        }
        Objects.requireNonNull(codes, "codes");
        Objects.requireNonNull(lut, "lut");
        Objects.requireNonNull(out, "out");
        if (groups <= 0 || capacity <= 0 || (blockSize != 8 && blockSize != 16 && blockSize != 32)) {
            throw new IllegalArgumentException("Expected positive groups/capacity and blockSize in {8,16,32}");
        }
        if (lut == out) {
            throw new IllegalArgumentException("ASH output must not alias the read-only query LUT");
        }
        long blockCount = (capacity - 1L) / blockSize + 1;
        long packedBytes = blockCount * (((groups + 1L) / 2 + HEADER_BYTES_PER_LANE) * blockSize);
        long lutFloats = groups * (long) LUT_ENTRIES_PER_GROUP;
        if (packedBytes > codes.length || lutFloats > lut.length || capacity > out.length) {
            throw new IndexOutOfBoundsException("ASH arrays are smaller than the configured neighborhood");
        }

        int status;
        long vectorSlots = blockCount * Math.max(blockSize, 16); // Native kernels cap FP32 width at 16.
        if ((long) groups * vectorSlots <= MAX_CRITICAL_LANE_GROUPS) {
            // These heap segments are valid only for this synchronous, short leaf call.
            status = invoke(CRITICAL_SCORE, MemorySegment.ofArray(codes), MemorySegment.ofArray(lut), landmarkDot,
                    groups, blockSize, capacity, MemorySegment.ofArray(out));
        } else {
            status = scoreLargeNeighborhood(
                    codes, packedBytes, lut, lutFloats, landmarkDot, groups, blockSize, capacity, out);
        }
        checkStatus(status);
    }

    private static int scoreLargeNeighborhood(byte[] codes, long packedBytes, float[] lut, long lutFloats,
            float landmarkDot, int groups, int blockSize, int capacity, float[] out) {
        try (Arena arena = Arena.ofConfined()) {
            MemorySegment nativeCodes = arena.allocate(packedBytes);
            MemorySegment nativeLut = arena.allocate(lutFloats * Float.BYTES, Float.BYTES);
            MemorySegment nativeOut = arena.allocate((long) capacity * Float.BYTES, Float.BYTES);
            MemorySegment.copy(MemorySegment.ofArray(codes), 0, nativeCodes, 0, packedBytes);
            MemorySegment.copy(MemorySegment.ofArray(lut), 0, nativeLut, 0, lutFloats * Float.BYTES);
            int status =
                    invoke(ORDINARY_SCORE, nativeCodes, nativeLut, landmarkDot, groups, blockSize, capacity, nativeOut);
            if (status == 0) {
                MemorySegment.copy(nativeOut, 0, MemorySegment.ofArray(out), 0, (long) capacity * Float.BYTES);
            }
            return status;
        }
    }

    private static int invoke(MethodHandle handle, MemorySegment codes, MemorySegment lut, float landmarkDot,
            int groups, int blockSize, int capacity, MemorySegment out) {
        if (TRACE_DOWNCALLS) {
            System.out.printf("%s(%d, %d, %d)%n", SYMBOL, groups, blockSize, capacity);
        }
        try {
            return (int) handle.invokeExact(codes, lut, landmarkDot, groups, blockSize, capacity, out);
        } catch (RuntimeException | Error error) {
            throw error;
        } catch (Throwable error) {
            throw new AssertionError("Unexpected checked exception from " + SYMBOL, error);
        }
    }

    private static void checkStatus(int status) {
        // These values are the C ABI contract documented in jvector_simd_kernel_list.h.
        switch (status) {
            case 0:
                return;
            case 1:
                throw new IllegalStateException("Invalid landmark in a C=1 FusedASH neighborhood");
            case 2:
                throw new IllegalArgumentException("Invalid native ASH neighborhood shape");
            default:
                throw new IllegalStateException("Unknown native ASH status: " + status);
        }
    }
}
